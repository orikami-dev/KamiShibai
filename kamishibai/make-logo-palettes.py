# Kamishibai mark in the colors of each interface palette (see res/values/kami_themes.xml).
# Same facets as make-logo.py; the red sheet takes the hue of the palette accent, the folded corner stays gold.
# Writes, for every palette but Washi (the original files): drawable/kami_logo_<p>.xml (top bar),
# drawable/kami_icon_foreground_<p>.xml + kami_icon_background_<p>.xml and mipmap-anydpi-v21/-v26/kami_icon_<p>.xml.
import colorsys, os, sys

RES = sys.argv[1]
SHEET = [("back", "#7A2A24", "M38,6L106,46L38,86Z"),
         ("dark", "#9E3830", "M26,40L50,54L26,54Z"),
         ("deep", "#61221E", "M26,54L50,54L26,94Z"),
         ("light", "#FF948C", "M47.76,26.8L94,54L50,54L26,40Z"),
         ("base", "#FF5A4E", "M50,54L94,54L26,94Z"),
         ("corner", "#FFD23F", "M26,40L47.76,26.8L49.1,52Z")]
# name: (accent used for the hue, or None to keep the vermilion sheet; tile color; corner color; brightness of the sheet)
PALETTES = {
    "sumi":   ("#6A4BC4", "#000000", "#FFD23F", 1.0),
    "ai":     ("#2B57A6", "#0A0D16", "#FFD23F", 1.0),
    "matcha": ("#4E7F2E", "#0B110A", "#FFD23F", 0.80),
    "sakura": ("#C8486F", "#160B10", "#FFD23F", 1.0),
    "kin":    ("#A87C00", "#13100A", "#FFF4D6", 0.92),
}

def rgb(h): return tuple(int(h[i:i + 2], 16) / 255 for i in (1, 3, 5))
def hexc(c): return "#" + "".join("%02X" % round(max(0, min(1, v)) * 255) for v in c)

def recolor(color, accent, bright):
    if accent is None:
        return color
    h, s, v = colorsys.rgb_to_hsv(*rgb(color))
    return hexc(colorsys.hsv_to_rgb(colorsys.rgb_to_hsv(*rgb(accent))[0], s, v * bright))

def stroke(color):
    return hexc(tuple(v * 0.55 for v in rgb(color)))

def paths(facets, ind):
    out = [ind + '<group android:translateX="1.8" android:translateY="3.2">']
    out += [ind + f'    <path android:fillColor="#38000000" android:strokeColor="#38000000" android:strokeWidth="1.4" android:strokeLineJoin="round" android:pathData="{d}" />' for _, d in facets]
    out.append(ind + '</group>')
    out += [ind + f'<path android:fillColor="#FF{c[1:]}" android:strokeColor="#FF{stroke(c)[1:]}" android:strokeWidth="1.4" android:strokeLineJoin="round" android:pathData="{d}" />' for c, d in facets]
    return out

def write(path, text):
    with open(os.path.join(RES, path), "w") as f:
        f.write('<?xml version="1.0" encoding="utf-8"?>\n' + text)

head = '<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="%s" android:height="%s" android:viewportWidth="108" android:viewportHeight="108">'
previews = []
for name, (accent, tile, corner, bright) in PALETTES.items():
    facets = [(corner if key == "corner" else recolor(c, accent, bright), d) for key, c, d in SHEET]
    note = f'<!-- Kamishibai mark, {name} palette. Generated by kamishibai/make-logo-palettes.py -->\n'
    write(f"drawable/kami_logo_{name}.xml", note + "\n".join([head % ("40dp", "40dp")] + paths(facets, "    ") + ["</vector>"]) + "\n")
    write(f"drawable/kami_icon_foreground_{name}.xml", note + "\n".join(
        [head % ("108dp", "108dp"), '    <group android:pivotX="62" android:pivotY="54" android:scaleX="0.56" android:scaleY="0.56" android:translateX="-5">']
        + paths(facets, "        ") + ["    </group>", "</vector>"]) + "\n")
    write(f"drawable/kami_icon_background_{name}.xml", note + head % ("108dp", "108dp")
          + f'\n    <path android:fillColor="#FF{tile[1:]}" android:pathData="M0,0h108v108h-108z" />\n</vector>\n')
    write(f"mipmap-anydpi-v26/kami_icon_{name}.xml", note + '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
          f'    <background android:drawable="@drawable/kami_icon_background_{name}" />\n'
          f'    <foreground android:drawable="@drawable/kami_icon_foreground_{name}" />\n'
          '    <monochrome android:drawable="@drawable/kami_icon_monochrome" />\n</adaptive-icon>\n')
    write(f"mipmap-anydpi-v21/kami_icon_{name}.xml", note + '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
          f'    <item android:drawable="@drawable/kami_icon_background_{name}" />\n'
          f'    <item android:drawable="@drawable/kami_icon_foreground_{name}" />\n</layer-list>\n')
    previews.append((tile, facets))

if len(sys.argv) > 2:  # preview PNG of the launcher icons, Washi first
    from PIL import Image, ImageDraw
    previews.insert(0, ("#120C0D", [(c, d) for _, c, d in SHEET]))
    img = Image.new("RGB", (len(previews) * 240 + 40, 280), "#2A2A2A")
    for i, (tile, facets) in enumerate(previews):
        ox = 40 + i * 240
        ImageDraw.Draw(img).rounded_rectangle((ox, 40, ox + 200, 240), 46, fill=tile)
        layer = Image.new("RGBA", img.size); dr = ImageDraw.Draw(layer)
        k = 200 / 108
        def pt(x, y): return (ox + ((x - 62) * 0.56 + 62 - 5) * k, 40 + ((y - 54) * 0.56 + 54) * k)
        for c, d in facets:
            xy = [tuple(map(float, q.split(","))) for q in d[1:-1].split("L")]
            dr.polygon([pt(x, y) for x, y in xy], fill=c, outline=stroke(c))
        img.paste(layer, (0, 0), layer)
    img.save(sys.argv[2])
