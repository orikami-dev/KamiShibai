# Kamishibai mark: an origami play sign folded from one sheet, drawn like the Origami crane
# (faceted, darker strokes, offset shadow). Writes the Android vectors and an SVG preview.
DEEP, DARK, BASE, LIGHT, GOLD = "#61221E", "#9E3830", "#FF5A4E", "#FF948C", "#FFD23F"
STROKE = {"#7A2A24": "#3D1512", DEEP: "#351210", DARK: "#561E1A", BASE: "#8C312A", LIGHT: "#8C514D", GOLD: "#8C7322"}
facets = [
    ("#7A2A24", "M38,6L106,46L38,86Z"),   # the next card of the story, waiting behind
    (DARK,  "M26,40L50,54L26,54Z"),          # upper left strip
    (DEEP,  "M26,54L50,54L26,94Z"),          # lower left strip, in the shade
    (LIGHT, "M47.76,26.8L94,54L50,54L26,40Z"),          # top face, in the light
    (BASE,  "M50,54L94,54L26,94Z"),          # bottom face
    (GOLD,  "M26,40L47.76,26.8L49.1,52Z"),          # corner folded over: the gold back of the sheet
]
def vector(scale_group=True, shadow=True):
    out = ['<vector xmlns:android="http://schemas.android.com/apk/res/android" android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">']
    if scale_group:
        out.append('    <group android:pivotX="62" android:pivotY="54" android:scaleX="0.7" android:scaleY="0.7" android:translateX="-6">')
    ind = "        " if scale_group else "    "
    if shadow:
        out.append(ind + '<group android:translateX="1.8" android:translateY="3.2">')
        for _, d in facets:
            out.append(ind + f'    <path android:fillColor="#38000000" android:strokeColor="#38000000" android:strokeWidth="1.4" android:strokeLineJoin="round" android:pathData="{d}" />')
        out.append(ind + '</group>')
    for c, d in facets:
        out.append(ind + f'<path android:fillColor="#FF{c[1:]}" android:strokeColor="#FF{STROKE[c][1:]}" android:strokeWidth="1.4" android:strokeLineJoin="round" android:pathData="{d}" />')
    if scale_group:
        out.append('    </group>')
    out.append('</vector>')
    return "\n".join(out) + "\n"
def svg(bg=True, size=256, scale=True):
    g = []
    if bg:
        g.append('<rect width="108" height="108" rx="24" fill="#120C0D"/>')
    t = 'transform="translate(62 54) scale(0.7) translate(-62 -54) translate(-9.1 0)"' if scale else ''
    g.append(f'<g {t}><g transform="translate(1.8 3.2)">' + "".join(f'<path d="{d}" fill="#000" fill-opacity=".22" stroke="#000" stroke-opacity=".22" stroke-width="1.4" stroke-linejoin="round"/>' for _, d in facets) + '</g>')
    g.append("".join(f'<path d="{d}" fill="{c}" stroke="{STROKE[c]}" stroke-width="1.4" stroke-linejoin="round"/>' for c, d in facets) + '</g>')
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="{size}" height="{size}" viewBox="0 0 108 108">' + "".join(g) + '</svg>'
